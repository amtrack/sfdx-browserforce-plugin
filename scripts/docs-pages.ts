/**
 * Navigation items as Zensical reads them: a list of single-key mappings at every level.
 * sfdx-hardis writes its `Commands` menu as nested mappings, which Zensical rejects ("Unknown nav item value type").
 */
export function toNavList(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(toNavList);
  }
  if (typeof value === 'object' && value !== null) {
    return Object.entries(value).map(([title, item]) => ({
      [title]: typeof item === 'string' ? item : toNavList(item),
    }));
  }
  return value;
}

/**
 * mkdocs.yml with the items of its top-level navigation entry `name` replaced (when `items` is given) and every
 * navigation entry written as lists; comments and layout are kept.
 */
export function updateNav(mkdocsYml: string, name: string, items?: unknown[]): string {
  const document = parseDocument(mkdocsYml);
  const nav = document.get('nav');
  if (!(nav instanceof YAMLSeq)) {
    throw new Error('mkdocs.yml has no "nav" list');
  }
  const entry = nav.items.find((item): item is YAMLMap => item instanceof YAMLMap && item.has(name));
  if (!entry) {
    throw new Error(`mkdocs.yml has no "${name}" entry in "nav"`);
  }
  if (items) {
    entry.set(name, document.createNode(items));
  }
  for (const item of nav.items) {
    if (item instanceof YAMLMap) {
      for (const pair of item.items) {
        if (pair.value instanceof YAMLMap) {
          pair.value = document.createNode(toNavList(pair.value.toJSON()));
        }
      }
    }
  }
  return document.toString({ lineWidth: 0 });
}

/**
 * Command page generated by sfdx-hardis with the oclif templates of its examples (`<%= config.bin %>`,
 * `<%= command.id %>`) replaced by `sf` and the command, as `sf <command> --help` shows them.
 */
export function renderCommandExamples(markdown: string): string {
  const commandId = /^# (\S+)$/m.exec(markdown)?.[1];
  if (!commandId) {
    return markdown;
  }
  return markdown
    .replace(/<%=\s*config\.bin\s*%>/g, 'sf')
    .replace(/<%=\s*command\.id\s*%>/g, commandId.replace(/:/g, ' '));
}
