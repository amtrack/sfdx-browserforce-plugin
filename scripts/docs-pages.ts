/** First line of the content of every page written by `npm run generate:docs`, after its front matter. */
export const GENERATED_HEADER =
  '<!-- This file is generated by `npm run generate:docs` from the zod schemas in src/plugins. Do not edit it. -->';

/** Longest description search engines show in their results. */
const MAX_DESCRIPTION_LENGTH = 160;

const FRONT_MATTER = /^---\r?\n[\s\S]*?\r?\n---\r?\n+/;

/** The page without its YAML front matter. */
export const removeFrontMatter = (markdown: string): string => markdown.replace(FRONT_MATTER, '');

/**
 * The page with a YAML front matter holding its title and description, which the site renders as `<title>` and
 * `<meta name="description">` for search engines; the theme appends the site name to the title. An existing front
 * matter is replaced.
 */
export function withFrontMatter(markdown: string, title: string, description: string): string {
  // Zensical does not escape double quotes in <meta name="description" content="...">: use typographic ones
  const typographic = (text: string): string => text.replace(/"([^"]*)"/g, '“$1”').replace(/"/g, '”');
  const yaml = stringify({ title: typographic(title), description: typographic(description) }, { lineWidth: 0 });
  return `---\n${yaml}---\n\n${removeFrontMatter(markdown)}`;
}

/** Plain text of a Markdown text: images, code marks, emphasis and link targets removed, on one line. */
export function plainText(markdown: string): string {
  return markdown
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*_]/g, '')
    .replace(/^\s*(?:#+|[-*]|\d+\.)\s+/gm, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** The first sentences of a text that fit in a search result description, cut at a word otherwise. */
export function summarize(text: string, maxLength = MAX_DESCRIPTION_LENGTH): string {
  if (text.length <= maxLength) {
    return text;
  }
  // a sentence ends with . ! or ? followed by a space: not inside "v36.0" or "AccountSettings.enableX"
  const sentences = text.split(/(?<=[.!?])\s+/).map((sentence) => `${sentence} `);
  let summary = '';
  for (const sentence of sentences) {
    if ((summary + sentence).trim().length > maxLength) {
      break;
    }
    summary += sentence;
  }
  if (summary.trim()) {
    return summary.trim();
  }
  return `${text.slice(0, maxLength - 1).replace(/\s+\S*$/, '')}…`;
}

/** Title and description of the page of a setting. */
export function settingPageMeta(
  entry: PluginCatalogEntry,
  description = entry.description,
): {
  title: string;
  description: string;
} {
  // the Setup menu path is in the page, the description says what the setting does:
  // "Name: Setup **A → B** (`/path`). Does this." becomes "Name: Does this."
  const body = (description ?? '')
    .split('\n')
    .filter((line) => !/^\s*Object Manager:/.test(line))
    .map((line) =>
      plainText(line).replace(/^((?:[^:]+: )?)(?:Salesforce Classic )?Setup:? .*?(?:\(\/[^)]*\)\.?\s*|$)/, '$1'),
    )
    .filter(Boolean)
    .join(' ');
  return {
    title: `${settingTitle(entry)} (settings.${entry.key})`,
    description: summarize(
      body ||
        `Apply ${settingTitle(entry)} in a Salesforce org with Browserforce, using the config key settings.${entry.key}.`,
    ),
  };
}

const SCHEMA_URL = rawFileUrl('src/plugins/schema.json');

const settingTitle = (entry: Pick<PluginCatalogEntry, 'key' | 'title'>): string => entry.title ?? entry.key;

/** Indents every non-empty line, for the content of admonitions and tabs. */
const indent = (text: string, spaces = 4): string =>
  text
    .split('\n')
    .map((line) => (line ? `${' '.repeat(spaces)}${line}` : line))
    .join('\n');

/** Text safe for a cell of a Markdown table. */
const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');

const code = (value: unknown): string => `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``;

/**
 * Image targets of a description, relative to the repository root, seen from a page of `docs/settings/`:
 * files of `docs/` stay on the site, other files of the repository are shown from GitHub.
 */
export function settingPageImage(target: string): string {
  const path = repositoryPath(target);
  return path.startsWith('docs/') ? `../${path.slice('docs/'.length)}` : rawFileUrl(path);
}

const jsonBlock = (value: unknown): string => ['```json', JSON.stringify(value, null, 2), '```'].join('\n');

const exampleConfig = (key: string, example: unknown): unknown => ({
  $schema: SCHEMA_URL,
  settings: { [key]: example },
});

function renderWarnings(entry: PluginCatalogEntry): string[] {
  const { userInterface, irreversibleFields, prerequisites } = entry.warnings;
  const blocks: string[] = [];
  if (userInterface) {
    const name = userInterface === 'classic' ? 'Salesforce Classic' : 'Lightning Experience';
    blocks.push(`!!! warning "${name} only"\n${indent(`This feature only exists in ${name}.`)}`);
  }
  if (irreversibleFields.length > 0) {
    blocks.push(
      `!!! danger "Irreversible"\n${indent(
        `Once applied, ${irreversibleFields.map(code).join(', ')} cannot be changed back.`,
      )}`,
    );
  }
  if (prerequisites.length > 0) {
    blocks.push(
      `!!! info "Prerequisites"\n${indent(prerequisites.map((prerequisite) => `- ${prerequisite}`).join('\n'))}`,
    );
  }
  return blocks;
}

function renderExamples(entry: PluginCatalogEntry): string[] {
  if (entry.examples.length === 0) {
    return [];
  }
  if (entry.examples.length === 1) {
    return ['## Example', jsonBlock(exampleConfig(entry.key, entry.examples[0]))];
  }
  return [
    '## Examples',
    entry.examples
      .map((example, index) => `=== "Example ${index + 1}"\n\n${indent(jsonBlock(exampleConfig(entry.key, example)))}`)
      .join('\n\n'),
  ];
}

function fieldNotes(field: Field): string[] {
  return [
    ...(field.required ? ['**Required.**'] : []),
    ...(field.isPassword ? ['**Secret:** masked in the output of `apply`.'] : []),
    ...(field.isIrreversible ? ['**Irreversible:** cannot be changed back once applied.'] : []),
  ];
}

/**
 * Path of a field as inline code that may wrap only after a dot (`picklistValues[].<wbr>metadataType`): a long path
 * does not widen the table, and a name is never cut in the middle.
 */
function fieldPath(path: string): string {
  const escaped = path.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '&#124;');
  return `<code>${escaped.replace(/\./g, '.<wbr>')}</code>`;
}

function renderFields(entry: PluginCatalogEntry): string[] {
  if (entry.fields.length === 0) {
    return [];
  }
  // the Values and Default columns only when a field has some
  const hasValues = entry.fields.some((field) => field.enum?.length);
  const hasDefaults = entry.fields.some((field) => field.default !== undefined);
  const header = [
    'Field',
    'Type',
    'Description',
    ...(hasValues ? ['Values'] : []),
    ...(hasDefaults ? ['Default'] : []),
  ];
  const rows = entry.fields.map((field) => {
    const description = [field.title, field.description]
      .filter((text): text is string => Boolean(text))
      .filter((text, index, texts) => texts.indexOf(text) === index);
    return [
      fieldPath(field.path),
      field.type,
      cell([...description, ...fieldNotes(field)].join('<br>')),
      ...(hasValues ? [cell((field.enum ?? []).map(code).join('<br>'))] : []),
      ...(hasDefaults ? [field.default === undefined ? '' : cell(code(field.default))] : []),
    ];
  });
  const lines = [
    `| ${header.join(' | ')} |`,
    `| ${header.map((title) => '-'.repeat(title.length)).join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ];
  const repeated = entry.groups.length
    ? ['In the field paths, `[]` stands for the items of a list and `*` for the entries of an object keyed by name.']
    : [];
  return ['## Fields', ...repeated, lines.join('\n')];
}

/** A pill number as a coloured badge, in the colour of the pill drawn on the images. */
export const pillBadge = (n: number): string => `<span class="bf-pill bf-pill-c${pillColorIndex(n)}">${n}</span>`;

/** Pill references of a text, `**(2)**` or `(2)` inside a bold run such as `**Save (3)**`, as coloured badges. */
export function renderPillReferences(markdown: string): string {
  return markdown.replace(BOLD_RUN, (bold, text: string) => {
    const withBadges = text.replace(PILL_CITATION, (_match, n: string) => pillBadge(Number(n)));
    return withBadges === text ? bold : `**${withBadges}**`;
  });
}

const legendValue = (value: unknown): string => (value === undefined ? '' : cell(code(value)));

function renderUseCaseImages(useCase: UseCase, state: 'before' | 'after', imageDir: string): string {
  const label = state === 'before' ? 'Before' : 'After';
  return useCase.captures
    .map((capture) => {
      const file = shotFileName(useCase.slug, capture.name, state, 'webp');
      const image = `![${label}: ${capture.title ?? useCase.title}](${imageDir}/${file})`;
      return useCase.captures.length > 1 ? `*${capture.title ?? capture.name}*\n\n${image}` : image;
    })
    .join('\n\n');
}

function legendRow(useCase: UseCase, pill: string, field: string, note?: string): string {
  const name = note ? `${fieldPath(field)}<br>${cell(note)}` : fieldPath(field);
  return `| ${pill} | ${name} | ${legendValue(valueAt(useCase.given, field))} | ${legendValue(
    valueAt(useCase.config, field),
  )} |`;
}

function renderUseCase(entry: PluginCatalogEntry, useCase: UseCase, heading: string, imageDir: string): string {
  const pills = numberPills(useCase);
  const rows = [
    ...pills.map((pill) => legendRow(useCase, pillBadge(pill.n), pill.field)),
    ...useCase.withoutPill.map((field) => legendRow(useCase, '', field.field, field.reason)),
  ];
  const legend = ['| Pill | Field | Before | After |', '| ---- | ----- | ------ | ----- |', ...rows].join('\n');
  const tabs = [`=== "Config"\n\n${indent(jsonBlock(exampleConfig(entry.key, useCase.config)))}`];
  if (!useCase.skip) {
    tabs.push(
      `=== "Before"\n\n${indent(renderUseCaseImages(useCase, 'before', imageDir))}`,
      `=== "After"\n\n${indent(renderUseCaseImages(useCase, 'after', imageDir))}`,
    );
  }
  return [
    heading,
    renderPillReferences(useCase.story),
    tabs.join('\n\n'),
    ...(useCase.skip ? [`!!! note "No screenshots"\n${indent(useCase.skip)}`] : []),
    ...(rows.length > 0 ? [legend] : []),
  ].join('\n\n');
}

/** Section "Use cases" of the page of a setting: story, config, annotated "Before" and "After" images and legend. */
export function renderUseCases(entry: PluginCatalogEntry, useCases: UseCase[]): string[] {
  if (useCases.length === 0) {
    return [];
  }
  const imageDir = `../assets/settings/${entry.key}`;
  return [
    useCases.length > 1 ? '## Use cases' : '## Use case',
    ...useCases.map((useCase, index) =>
      renderUseCase(
        entry,
        useCase,
        useCases.length > 1 ? `### ${index + 1}. ${useCase.title}` : `### ${useCase.title}`,
        imageDir,
      ),
    ),
  ];
}

export type SettingPageOptions = {
  /**
   * Markdown description of the setting with the image paths relative to the repository root, as written in its
   * schema (the catalog already turned them into raw URLs). Defaults to the catalog description.
   */
  description?: string;
  /** link to the source folder of the plugin */
  sourceUrl?: string;
  /** use cases of the setting, in the order of their files */
  useCases?: UseCase[];
};

/** Page `docs/settings/<key>.md` of a setting. */
export function renderSettingPage(entry: PluginCatalogEntry, options: SettingPageOptions = {}): string {
  const description = options.description ?? entry.description;
  const sections = [
    GENERATED_HEADER,
    `# ${settingTitle(entry)}`,
    `Config key: \`settings.${entry.key}\``,
    ...renderWarnings(entry),
    ...(description ? [rewriteMarkdownImages(description.trim(), settingPageImage)] : []),
    ...renderUseCases(entry, options.useCases ?? []),
    ...renderExamples(entry),
    ...renderFields(entry),
    `??? note "JSON Schema"\n\n${indent(jsonBlock(entry.jsonSchema))}`,
    ...(options.sourceUrl ? [`[Source code of this setting](${options.sourceUrl})`] : []),
  ];
  const meta = settingPageMeta(entry, description);
  return withFrontMatter(`${sections.join('\n\n')}\n`, meta.title, meta.description);
}

const hallOfFameLink = (deprecated: DeprecatedSetting): string => {
  const anchor = deprecated.url.split('#')[1];
  return `../hall-of-fame.md${anchor ? `#${anchor}` : ''}`;
};

/** Page `docs/settings/index.md` listing every setting and the removed ones. */
export function renderSettingsIndex(entries: PluginCatalogEntry[], deprecatedSettings: DeprecatedSetting[]): string {
  const warnings = (entry: PluginCatalogEntry): string =>
    [
      entry.warnings.userInterface ? `${entry.warnings.userInterface} only` : undefined,
      entry.warnings.irreversibleFields.length > 0 ? 'irreversible' : undefined,
      entry.warnings.prerequisites.length > 0 ? 'prerequisites' : undefined,
    ]
      .filter(Boolean)
      .join(', ');
  const sorted = entries.toSorted((a, b) => settingTitle(a).localeCompare(settingTitle(b)));
  const sections = [
    GENERATED_HEADER,
    '# Settings',
    'Each setting is a key under `settings` in a Browserforce config file. ' +
      '`sf browserforce plugins list` lists them too, without connecting to an org.',
    [
      '| Setting | Config key | Warnings |',
      '| ------- | ---------- | -------- |',
      ...sorted.map(
        (entry) => `| [${cell(settingTitle(entry))}](${entry.key}.md) | \`${entry.key}\` | ${warnings(entry)} |`,
      ),
    ].join('\n'),
  ];
  if (deprecatedSettings.length > 0) {
    sections.push(
      '## Removed settings',
      'These settings have been removed, most of them because Salesforce now supports them in the Metadata API.',
      [
        '| Config key | Why | Instructions |',
        '| ---------- | --- | ------------ |',
        ...deprecatedSettings.map(
          (deprecated) =>
            `| \`${deprecated.path}\` | ${cell(deprecated.message)} | [Hall of Fame](${hallOfFameLink(deprecated)}) |`,
        ),
      ].join('\n'),
    );
  }
  return withFrontMatter(
    `${sections.join('\n\n')}\n`,
    'Settings reference',
    summarize(
      `The ${entries.length} Salesforce Setup settings Browserforce can apply with their config keys and warnings, ` +
        'and the settings removed since the Metadata API supports them.',
    ),
  );
}

