/** Index (1 to 20) of the colour of a pill, for the CSS class `bf-pill-c<index>`. */
export function pillColorIndex(n: number): number {
  return ((n - 1) % PILL_PALETTE.length) + 1;
}

export function pillColor(n: number): string {
  return PILL_PALETTE[pillColorIndex(n) - 1];
}

/** Stylesheet of the pills cited in the text of the pages, in the colours of the pills of the images. */
export function renderPillsCss(): string {
  return [
    '/* Generated by `npm run generate:docs` from PILL_PALETTE in scripts/screenshots.ts. Do not edit it. */',
    '.bf-pill {',
    '  display: inline-block;',
    '  min-width: 1.6em;',
    '  padding: 0 0.35em;',
    '  border-radius: 0.8em;',
    '  color: #fff;',
    '  font-weight: 700;',
    '  font-size: 0.8em;',
    '  line-height: 1.6em;',
    '  text-align: center;',
    '  vertical-align: 0.1em;',
    '}',
    ...PILL_PALETTE.map((color, index) => `.bf-pill-c${index + 1} {\n  background-color: ${color};\n}`),
    '',
  ].join('\n');
}

export type Box = { x: number; y: number; width: number; height: number };

export type ShotPill = { n: number; field: string; box: Box };

/** One image of a capture: the raw screenshot of the whole viewport and the boxes of its controls. */
export type ShotRecord = { file: string; pills: ShotPill[] };

/** A pill of a capture: its number, the field it shows, and the images where its control is. */
export type RecordedPill = { n: number; field: string; in: 'both' | 'before' | 'after' };

export type CaptureRecord = {
  name: string;
  viewport: { width: number; height: number };
  /** the pills declared by the `doc.shot()` of the capture, in their order */
  pills: RecordedPill[];
  /** part of the viewport kept in the documentation images, the same for "Before" and "After" */
  clip: Box;
  before: ShotRecord;
  after: ShotRecord;
};

export type UseCaseRecord = {
  /** `captureHash()` of the use case when it was captured */
  hash: string;
  capturedAt: string;
  captures: CaptureRecord[];
};

/** `screenshots/<key>/capture.json` */
export type SettingRecord = { useCases: Record<string, UseCaseRecord> };

const recordUrl = (root: URL, key: string): URL => new URL(`screenshots/${key}/capture.json`, root);

export function readSettingRecord(root: URL, key: string): SettingRecord | undefined {
  const file = recordUrl(root, key);
  return existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as SettingRecord) : undefined;
}

/** Writes the record of a setting with its use cases sorted, so a capture only changes its own lines. */
export function writeSettingRecord(root: URL, key: string, record: SettingRecord): void {
  mkdirSync(new URL(`screenshots/${key}/`, root), { recursive: true });
  const sorted: SettingRecord = {
    useCases: Object.fromEntries(Object.entries(record.useCases).sort(([a], [b]) => a.localeCompare(b))),
  };
  writeFileSync(
    recordUrl(root, key),
    `${JSON.stringify(sorted, null, 2)}
`,
  );
}

const PADDING = 40;
const MIN_WIDTH = 960;
const MIN_HEIGHT = 420;

/**
 * Part of the viewport kept around the controls of both images (and the `context` of the capture): their union with a
 * margin for the pills, at least 960×420 and inside the viewport.
 */
export function computeClip(pills: Box[], context: Box[], viewport: { width: number; height: number }): Box {
  if (pills.length + context.length === 0) {
    return { x: 0, y: 0, width: viewport.width, height: viewport.height };
  }
  // the pills need a margin around their controls, the context is taken as it is
  const boxes = [
    ...pills.map((box) => ({
      x: box.x - PADDING,
      y: box.y - PADDING,
      width: box.width + 2 * PADDING,
      height: box.height + 2 * PADDING,
    })),
    ...context,
  ];
  const span = (start: number, end: number, min: number, max: number): [number, number] => {
    let low = start;
    let high = end;
    if (high - low < min) {
      const missing = min - (high - low);
      low -= missing / 2;
      high += missing / 2;
    }
    if (low < 0) {
      high -= low;
      low = 0;
    }
    if (high > max) {
      low = Math.max(0, low - (high - max));
      high = max;
    }
    return [Math.floor(low), Math.ceil(high)];
  };
  const [x1, x2] = span(
    Math.min(...boxes.map((box) => box.x)),
    Math.max(...boxes.map((box) => box.x + box.width)),
    MIN_WIDTH,
    viewport.width,
  );
  const [y1, y2] = span(
    Math.min(...boxes.map((box) => box.y)),
    Math.max(...boxes.map((box) => box.y + box.height)),
    MIN_HEIGHT,
    viewport.height,
  );
  return { x: x1, y: y1, width: x2 - x1, height: y2 - y1 };
}

export const PILL_RADIUS = 13;
const GAP = 6;

/** Width of a pill: a circle for one digit, a capsule for more. */
export const pillWidth = (n: number): number =>
  n < 10 ? 2 * PILL_RADIUS : 2 * PILL_RADIUS + 8 * (String(n).length - 1);

/** A pill as drawn on the clipped image: the box of its control and the center of the pill. */
export type DrawnPill = { n: number; color: string; box: Box; cx: number; cy: number };

/**
 * Where a pill goes on the clipped image: right of its control (the label of a Setup field is on its left), else left,
 * else above, else inside its top left corner, so it covers nothing the reader has to read; `px`/`py` (% of the
 * image) override it.
 */
export function placePill(
  pill: { n: number; box: Box; px?: number; py?: number },
  image: { width: number; height: number },
): DrawnPill {
  const { box } = pill;
  const half = pillWidth(pill.n) / 2;
  const middle = box.y + Math.min(box.height / 2, PILL_RADIUS + 2);
  const candidates: Array<[number, number]> = [
    [box.x + box.width + GAP + half, middle],
    [box.x - GAP - half, middle],
    [box.x + half, box.y - GAP - PILL_RADIUS],
  ];
  const fits = ([cx, cy]: [number, number]): boolean =>
    cx - half >= 0 && cx + half <= image.width && cy - PILL_RADIUS >= 0 && cy + PILL_RADIUS <= image.height;
  let [cx, cy] = candidates.find(fits) ?? [box.x + half + 2, box.y + PILL_RADIUS + 2];
  if (pill.px !== undefined) {
    cx = (pill.px / 100) * image.width;
  }
  if (pill.py !== undefined) {
    cy = (pill.py / 100) * image.height;
  }
  return { n: pill.n, color: pillColor(pill.n), box, cx: Math.round(cx), cy: Math.round(cy) };
}

/** Box of a control in the clipped image. */
export function toClip(box: Box, clip: Box): Box {
  return { x: box.x - clip.x, y: box.y - clip.y, width: box.width, height: box.height };
}

/** Quality of the WebP images of the documentation: text stays sharp, files are about 5 times smaller than PNG. */
export const WEBP_QUALITY = 0.9;

/** Changes whenever the drawing changes, so every image is drawn again. */
export const RENDER_VERSION = 1;

/** Stamp of an annotated image: changes when its raw screenshot, its clip or its pills change. */
export function annotationStamp(raw: Buffer, clip: Box, pills: DrawnPill[]): string {
  return createHash('sha256')
    .update(raw)
    .update(JSON.stringify({ clip, pills, version: RENDER_VERSION, quality: WEBP_QUALITY, palette: PILL_PALETTE }))
    .digest('hex');
}

/** File name of an image: `<use case>-<capture>-<before|after>.<extension>` */
export function shotFileName(slug: string, capture: string, state: 'before' | 'after', extension: string): string {
  return `${slug}-${capture}-${state}.${extension}`;
}

